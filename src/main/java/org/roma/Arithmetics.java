package org.roma;

public class Arithmetics {
    public static long sum(int a, int b) {
        return a + b;
    }

    public static int diff(int a, int b) {
        return a - b;
    }

    public static long multiply(int a, int b) {
        return a * b;
    }

    public static double divide(int a, int b) {
        return (double)a / (double)b;
    }
}
